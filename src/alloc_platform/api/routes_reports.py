"""Export endpoints for experiment reports in Markdown, CSV, and JSON formats."""

import csv
import io
import json

from fastapi import APIRouter, Depends, HTTPException, Response
from sqlalchemy.orm import Session

from alloc_platform.db.models import Run
from alloc_platform.db.repo import get_experiment_by_id, get_run_metrics
from alloc_platform.db.session import get_db

reports_router = APIRouter(prefix="/reports")


@reports_router.get("/{experiment_id}.json")
@reports_router.get("/json/{experiment_id}")
def export_json(experiment_id: str, db: Session = Depends(get_db)):
    exp = get_experiment_by_id(db, experiment_id)
    if not exp:
        raise HTTPException(status_code=404, detail="Experiment not found")

    runs = db.query(Run).filter(Run.experiment_id == experiment_id).all()
    runs_data = []
    for r in runs:
        m = get_run_metrics(db, r.id)
        runs_data.append(
            {
                "run_id": r.id,
                "policy": r.policy,
                "repeat": r.repeat_index,
                "is_valid": r.is_valid,
                "invalidation_reason": r.invalidation_reason,
                "metrics": m,
            }
        )

    report = {
        "experiment_id": exp.id,
        "name": exp.name,
        "scenario_id": exp.scenario_id,
        "status": exp.status,
        "created_at": exp.created_at.isoformat(),
        "completed_at": exp.completed_at.isoformat() if exp.completed_at else None,
        "runs": runs_data,
    }
    return Response(
        content=json.dumps(report, indent=2),
        media_type="application/json",
        headers={"Content-Disposition": f"attachment; filename=report_{experiment_id}.json"},
    )


@reports_router.get("/{experiment_id}.csv")
@reports_router.get("/csv/{experiment_id}")
def export_csv(experiment_id: str, db: Session = Depends(get_db)):
    exp = get_experiment_by_id(db, experiment_id)
    if not exp:
        raise HTTPException(status_code=404, detail="Experiment not found")

    runs = db.query(Run).filter(Run.experiment_id == experiment_id).all()
    output = io.StringIO()
    writer = csv.writer(output)

    # Header
    writer.writerow(
        ["experiment_id", "run_id", "policy", "repeat", "is_valid", "metric_name", "metric_value"]
    )
    for r in runs:
        m = get_run_metrics(db, r.id)
        for k, v in m.items():
            writer.writerow([exp.id, r.id, r.policy, r.repeat_index, r.is_valid, k, v])

    return Response(
        content=output.getvalue(),
        media_type="text/csv",
        headers={"Content-Disposition": f"attachment; filename=report_{experiment_id}.csv"},
    )


@reports_router.get("/{experiment_id}.md")
@reports_router.get("/markdown/{experiment_id}")
@reports_router.get("/{experiment_id}.markdown")
def export_markdown(experiment_id: str, db: Session = Depends(get_db)):
    exp = get_experiment_by_id(db, experiment_id)
    if not exp:
        raise HTTPException(status_code=404, detail="Experiment not found")

    runs = db.query(Run).filter(Run.experiment_id == experiment_id).all()
    lines = [
        f"# Evaluation Report: {exp.name}",
        f"**Experiment ID:** `{exp.id}`  ",
        f"**Scenario:** `{exp.scenario_id}`  ",
        f"**Status:** `{exp.status}`  ",
        f"**Created:** `{exp.created_at.isoformat()}`  \n",
        "## Summary of Results Across Allocation Policies\n",
        "| Policy | Run ID | Jain Fairness (Primary) | Mean Satisfaction | Allocation Churn | Average Solve Time (ms) |",
        "|---|---|---|---|---|---|",
    ]

    for r in runs:
        m = get_run_metrics(db, r.id)
        jain = f"{m.get('jain_fairness_primary', 0.0):.4f}"
        sat = f"{m.get('mean_satisfaction', 0.0):.4f}"
        ch = f"{m.get('churn', 0.0):.4f}"
        solve = f"{m.get('solve_ms_avg', 0.0):.2f}"
        lines.append(f"| {r.policy.upper()} | `{r.id}` | {jain} | {sat} | {ch} | {solve} |")

    lines.append("\n*Generated by the Adaptive Multi-Tenant Cloud Resource Allocation Platform*")
    return Response(
        content="\n".join(lines),
        media_type="text/markdown",
        headers={"Content-Disposition": f"attachment; filename=report_{experiment_id}.md"},
    )


export_router = APIRouter(prefix="/api/v1/export")

@export_router.get("/{experiment_id}.json")
@export_router.get("/json/{experiment_id}")
def export_json_api(experiment_id: str, db: Session = Depends(get_db)):
    return export_json(experiment_id, db)

@export_router.get("/{experiment_id}.csv")
@export_router.get("/csv/{experiment_id}")
def export_csv_api(experiment_id: str, db: Session = Depends(get_db)):
    return export_csv(experiment_id, db)

@export_router.get("/{experiment_id}.md")
@export_router.get("/markdown/{experiment_id}")
@export_router.get("/{experiment_id}.markdown")
def export_markdown_api(experiment_id: str, db: Session = Depends(get_db)):
    return export_markdown(experiment_id, db)
